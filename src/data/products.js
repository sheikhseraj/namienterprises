export function getProductBySlug(slug) {
  return products.find(p => p.slug === slug)
}

export function getRelatedProducts(product, count = 4) {
  return products
    .filter(p => p.id !== product.id && (p.category === product.category || p.subCategory === product.subCategory))
    .slice(0, count)
}

export function buildWhatsAppUrl(product, size, color, qty = 1) {
  const msg = `Hi Nami Enterprises! 👋\n\nI'd like to order:\n\n*${product.name}*\nSize: ${size}\nColor: ${color}\nQuantity: ${qty}\nPrice: ₹${product.price.toLocaleString('en-IN')}\n\nPlease confirm availability and share payment details. Thank you!`
  return `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(msg)}`
}
